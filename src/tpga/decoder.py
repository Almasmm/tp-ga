"""Greedy decoder: permutation of arcs -> feasible shipment plan."""

from __future__ import annotations

import numpy as np
from numpy.typing import ArrayLike, NDArray

from tpga.model import FloatArray, TransportProblem

#: Relative tolerance of the decoder's zero test (see :func:`decoder_eps`).
DECODER_TOL = 1e-12


def decoder_eps(problem: TransportProblem, tol: float = DECODER_TOL) -> float:
    """Threshold below which a remaining supply or demand counts as zero: ``tol * max(1, max a, max b)``.

    With integer data every remaining amount is 0 or at least 1, so any threshold below 1 gives the same
    plans as the exact test ``== 0`` of v0.3.0.
    """
    return float(tol * max(1.0, float(np.max(problem.supply)), float(np.max(problem.demand))))


def decode_permutation(problem: TransportProblem, perm: ArrayLike, tol: float = DECODER_TOL) -> FloatArray:
    """Decode a permutation of the ``m * n`` arcs into a shipment plan.

    Arcs are visited in permutation order (arc ``k`` is ``(k // n, k % n)``) and each receives
    ``x_ij = min(remaining a_i, remaining b_j)``; a remainder ``<= decoder_eps(problem, tol)`` counts as zero.

    For a *balanced* problem with nonnegative supplies and demands and a complete arc set the result
    satisfies the supply, demand and nonnegativity constraints and is a basic feasible solution (at most
    ``m + n - 1`` positive cells, acyclic support). Conversely, every basic feasible solution, an optimal
    one included, is the decoding of some permutation (Proposition 2 of the article; the leaf-elimination
    construction is :func:`tpga.basis.permutation_from_basis`, checked by
    ``tests/test_properties.py::test_permutation_from_the_optimal_basis_decodes_to_the_optimum`` and in
    ``paper_artifacts/reachability.json``). The decoder does not handle arc capacities, fixed charges or
    time windows, and a particular permutation says nothing about optimality. Cost: ``O(m * n)``.

    Raises
    ------
    ValueError
        If the problem is unbalanced or ``perm`` is not a permutation of ``range(m * n)``.
    """
    if not problem.is_balanced:
        raise ValueError("the decoder requires a balanced problem; call problem.balanced() first")
    m, n = problem.shape
    p = np.asarray(perm, dtype=np.int64).ravel()
    if p.size != m * n or not np.array_equal(np.sort(p), np.arange(m * n)):
        raise ValueError(f"perm must be a permutation of range({m * n})")
    return _decode_valid_permutation(problem, p, decoder_eps(problem, tol))


def decode_trace(problem: TransportProblem, perm: ArrayLike, tol: float = DECODER_TOL) -> list[dict]:
    """Step-by-step record of :func:`decode_permutation`, one entry per visited arc.

    Each entry gives the position in the permutation, the arc, the allocated quantity (zero when
    the row or the column is already exhausted) and the remaining supplies and demands after it.
    Arcs after the point where every supply is exhausted are not visited.
    """
    x = decode_permutation(problem, perm, tol)  # validates and gives the reference result
    eps = decoder_eps(problem, tol)
    m, n = problem.shape
    supply, demand = problem.supply.tolist(), problem.demand.tolist()
    steps: list[dict] = []
    active = sum(value > eps for value in supply)
    for position, index in enumerate(np.asarray(perm, dtype=np.int64).ravel().tolist()):
        if not active:
            break
        i, j = divmod(int(index), n)
        quantity = min(supply[i], demand[j])
        if quantity > eps:
            supply[i] -= quantity
            demand[j] -= quantity
            if supply[i] <= eps:
                active -= 1
        else:
            quantity = 0.0
        steps.append(
            {
                "position": position,
                "arc": int(index),
                "row": i,
                "col": j,
                "quantity": float(max(quantity, 0.0)),
                "supply_left": list(supply),
                "demand_left": list(demand),
            }
        )
    plan = np.zeros((m, n))
    for step in steps:
        plan[int(step["row"]), int(step["col"])] += float(step["quantity"])
    if not np.array_equal(plan, x):  # pragma: no cover - both loops implement the same rule
        raise AssertionError("trace disagrees with the decoder")
    return steps


def _decode_valid_permutation(
    problem: TransportProblem, permutation: NDArray[np.int64], eps: float = 0.0
) -> FloatArray:
    """Decode a permutation already validated or generated by the GA (independent reference code)."""
    m, n = problem.shape
    supply, demand = problem.supply.tolist(), problem.demand.tolist()
    active = sum(value > eps for value in supply)
    plan = np.zeros((m, n))
    for index in permutation:
        if not active:
            break
        i, j = divmod(int(index), n)
        quantity = min(supply[i], demand[j])
        if quantity > eps:
            plan[i, j] = quantity
            supply[i] -= quantity
            demand[j] -= quantity
            if supply[i] <= eps:
                active -= 1
    return plan
