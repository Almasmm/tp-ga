"""Instance sets of the experiment, written to ``instances/`` with a SHA-256 manifest."""

from __future__ import annotations

import hashlib
import json
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from tpga.experiments.config import Config
from tpga.model import TransportProblem


@dataclass(frozen=True)
class Instance:
    id: str
    suite: str
    m: int
    n: int
    path: Path
    seed: int | None
    balanced: bool

    @property
    def size(self) -> str:
        return f"{self.m}x{self.n}"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def uniform_instance(m: int, n: int, seed: int, spec: dict[str, Any]) -> dict[str, Any]:
    """Integer costs ``U[cost_low, cost_high]``; integer supplies ``U[supply_low, supply_high]``;
    demands are ``1 + multinomial(S - n, equal shares)`` so that they are positive and sum to ``S``."""
    rng = np.random.default_rng(seed)
    a = rng.integers(int(spec["supply_low"]), int(spec["supply_high"]) + 1, size=m)
    total = int(a.sum())
    if total < n:
        raise ValueError("total supply must be at least the number of destinations")
    b = 1 + rng.multinomial(total - n, np.full(n, 1 / n))
    c = rng.integers(int(spec["cost_low"]), int(spec["cost_high"]) + 1, size=(m, n))
    return {"supply": a.tolist(), "demand": b.tolist(), "cost": c.tolist()}


def structured_instance(m: int, n: int, seed: int, spec: dict[str, Any]) -> dict[str, Any]:
    """Sources and destinations uniform on ``[0, area]^2``; ``c_ij = 1 + round(d_ij + U[0, noise])``
    where ``d_ij`` is the Euclidean distance; supplies and demands as in :func:`uniform_instance`."""
    rng = np.random.default_rng(seed)
    area, noise = float(spec["area"]), float(spec["noise"])
    src = rng.uniform(0, area, size=(m, 2))
    dst = rng.uniform(0, area, size=(n, 2))
    d = np.linalg.norm(src[:, None, :] - dst[None, :, :], axis=2)
    c = 1 + np.rint(d + rng.uniform(0, noise, size=(m, n))).astype(int)
    a = rng.integers(int(spec["supply_low"]), int(spec["supply_high"]) + 1, size=m)
    b = 1 + rng.multinomial(int(a.sum()) - n, np.full(n, 1 / n))
    return {
        "supply": a.tolist(),
        "demand": b.tolist(),
        "cost": c.tolist(),
        "coordinates": {"sources": np.round(src, 4).tolist(), "destinations": np.round(dst, 4).tolist()},
    }


def _write(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, separators=(",", ":")) + "\n", encoding="utf-8")


def _seed(base: int, suite_offset: int, size_index: int, k: int) -> int:
    return base + 1_000_000 * suite_offset + 1000 * size_index + k


def build(cfg: Config) -> list[Instance]:
    """Generate (or verify) every instance and write ``instances/manifest.json``. Idempotent."""
    root = cfg.output / "instances"
    spec = cfg.raw["instances"]
    entries: list[dict[str, Any]] = []
    out: list[Instance] = []
    generators = {"uniform": (uniform_instance, 1), "structured": (structured_instance, 2)}
    for suite, (gen, offset) in generators.items():
        if suite not in spec:
            continue
        s = spec[suite]
        for size_index, (m, n) in enumerate(s["sizes"]):
            for k in range(int(s["per_size"])):
                seed = _seed(cfg.base_seed, offset, size_index, k)
                iid = f"{suite[0]}{m}x{n}-{k:02d}"
                path = root / suite / f"{iid}.json"
                data = gen(int(m), int(n), seed, s)
                expected = json.dumps(data, separators=(",", ":")) + "\n"
                if not path.exists() or path.read_text(encoding="utf-8") != expected:
                    _write(path, data)
                entries.append(
                    {
                        "id": iid,
                        "suite": suite,
                        "m": int(m),
                        "n": int(n),
                        "seed": seed,
                        "file": path.relative_to(root).as_posix(),
                        "sha256": sha256(path),
                        "balanced": True,
                        "provenance": f"generated by tpga.experiments.instances.{gen.__name__} with seed {seed}",
                    }
                )
                out.append(Instance(iid, suite, int(m), int(n), path, seed, True))
    applied = spec.get("applied")
    if applied:
        for dataset in applied["datasets"]:
            src_root = cfg.root / "datasets" / dataset
            manifest = json.loads((src_root / "manifest.json").read_text(encoding="utf-8"))
            for sc in manifest["scenarios"]:
                if sc.get("event") in applied.get("exclude_events", []):
                    continue
                src = src_root / sc["file"]
                iid = f"{dataset}/{sc['id']}"
                path = root / "applied" / dataset / Path(sc["file"]).name
                path.parent.mkdir(parents=True, exist_ok=True)
                if not path.exists() or sha256(path) != sha256(src):
                    shutil.copyfile(src, path)
                p = TransportProblem.from_json(path)
                m, n = p.shape
                entries.append(
                    {
                        "id": iid,
                        "suite": "applied",
                        "dataset": dataset,
                        "m": m,
                        "n": n,
                        "seed": None,
                        "file": path.relative_to(root).as_posix(),
                        "source_file": src.relative_to(cfg.root).as_posix(),
                        "sha256": sha256(path),
                        "balanced": p.is_balanced,
                        "total_supply": float(p.supply.sum()),
                        "total_demand": float(p.demand.sum()),
                        "event": sc.get("event"),
                        "units": manifest.get("units"),
                        "data_kind": manifest.get("data_kind"),
                        "provenance": applied.get("provenance", {}).get(dataset, manifest.get("data_kind")),
                        "dataset_sources": manifest.get("sources"),
                    }
                )
                out.append(Instance(iid, "applied", m, n, path, None, p.is_balanced))
    (root / "manifest.json").write_text(
        json.dumps({"base_seed": cfg.base_seed, "instances": entries}, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
    )
    return out
