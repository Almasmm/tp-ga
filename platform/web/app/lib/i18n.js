export const DICT = { ru, en };

export function translate(lang, key, vars) {
  let s = (DICT[lang] ?? ru)[key] ?? ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
